#!/usr/bin/env python3
"""Generate the NT36523 panel data header from the extracted vendor profile.

The 359 downstream init commands, the timings and the reset delays are data, not
logic: keep them generated from hardware/samsung/gts7lwifi/panel/*.json so they
cannot drift from the vendor source by hand-editing.

    scripts/steamos/emit-panel-seq.py            # rewrite the header
    scripts/steamos/emit-panel-seq.py --check    # verify it is up to date

The generated header lands in the kernel tree next to the driver that includes
it. Nothing here touches hardware.
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
PROFILE = ROOT / 'hardware/samsung/gts7lwifi/panel/nt36523-ppa957db1.json'
HEADER = (ROOT / 'linux-sm8250-v6.18/drivers/gpu/drm/panel/'
          'panel-novatek-nt36523-gts7lwifi.h')
MAX_PAYLOAD = 16


def sha(data):
    return hashlib.sha256(data if isinstance(data, bytes) else data.encode()).hexdigest()


def mode_numbers(profile):
    """Full-panel mode values; msm halves horizontal timings for bonded DSI."""
    timing = profile['timing']
    links = max(1, profile['link']['topology'][0]) if profile['link']['topology'] else 2
    width = timing['width'] * 2              # the vendor value is per link
    height = timing['height']
    hfp = timing['h_front_porch'] * 2        # halved again per link by msm
    hsw = timing['h_pulse_width'] * 2
    hbp = timing['h_back_porch'] * 2
    vfp = timing['v_front_porch']
    vsw = timing['v_pulse_width']
    vbp = timing['v_back_porch']
    htotal = width + hfp + hsw + hbp
    vtotal = height + vfp + vsw + vbp
    fps = timing['framerate']
    clock = round(htotal * vtotal * fps / 1000)
    return {
        'links': links,
        'clock': clock, 'hdisplay': width, 'hfp': hfp, 'hsw': hsw, 'hbp': hbp,
        'hsync_start': width + hfp, 'hsync_end': width + hfp + hsw, 'htotal': htotal,
        'vdisplay': height, 'vfp': vfp, 'vsw': vsw, 'vbp': vbp,
        'vsync_start': height + vfp, 'vsync_end': height + vfp + vsw, 'vtotal': vtotal,
        'fps': fps,
    }


def emit(profile):
    panel = profile['panel']
    link = profile['link']
    brightness = profile['brightness']
    numbers = mode_numbers(profile)
    commands = profile['init_sequence']['commands']
    source = profile['provenance']['files']['dsi_panel_NT36523_PPA957DB1_wqxga_video.dtsi']

    longest = max(len(command['payload']) for command in commands)
    if longest > MAX_PAYLOAD:
        raise ValueError(f'init payload needs {longest} bytes, raise MAX_PAYLOAD')

    lines = [
        '/* SPDX-License-Identifier: GPL-2.0-only */',
        '/*',
        ' * Generated by scripts/steamos/emit-panel-seq.py -- do not edit by hand.',
        f' * Panel: {panel["name"]} ({panel["display_model"]}, vendor {panel["vendor"]})',
        f' * Profile: hardware/samsung/gts7lwifi/panel/nt36523-ppa957db1.json',
        f' *   profile sha256        {sha(PROFILE.read_bytes())}',
        f' *   vendor dtsi sha256    {source["sha256"]}',
        ' *',
        ' * The vendor DTS describes one DSI link: {timing_width}x{timing_height} with'.format(
            timing_width=profile['timing']['width'], timing_height=profile['timing']['height']),
        f' * {numbers["links"]} links bonded. msm halves the horizontal timings per link, so the',
        ' * DRM mode below carries the full panel width and doubled horizontal porches.',
        ' */',
        '',
        '#ifndef __PANEL_NOVATEK_NT36523_GTS7LWIFI_H__',
        '#define __PANEL_NOVATEK_NT36523_GTS7LWIFI_H__',
        '',
        f'#define PPA957DB1_RESET_DELAY_MS\t{link["reset_sequence"][0][1]}',
        f'#define PPA957DB1_PHYSICAL_WIDTH_MM\t{panel["physical_width_mm"]}',
        f'#define PPA957DB1_PHYSICAL_HEIGHT_MM\t{panel["physical_height_mm"]}',
        f'#define PPA957DB1_BRIGHTNESS_MAX\t{brightness["max_level"]}',
        f'#define PPA957DB1_BRIGHTNESS_MIN\t{brightness["min_level"]}',
        f'#define PPA957DB1_INIT_CMDS\t\t{len(commands)}',
        '',
        '/*',
        ' * Init commands in vendor order. delay_ms is the vendor wait after the',
        ' * command; len counts the payload bytes that start with the DCS command.',
        ' */',
        'static const struct nt36523_init_cmd ppa957db1_init[] = {',
    ]
    for index, command in enumerate(commands):
        payload = command['payload'][1:]
        delay = command['wait'][0]
        raw = ', '.join(f'0x{value:02x}' for value in payload)
        lines.append(f'\t{{ {len(payload):2d}, {delay:3d}, {{ {raw} }} }},'
                     f'\t/* {index:3d} */')
    lines += [
        '};',
        '',
        'static const struct drm_display_mode ppa957db1_mode = {',
        f'\t.clock\t\t= {numbers["clock"]},',
        f'\t.hdisplay\t= {numbers["hdisplay"]},',
        f'\t.hsync_start\t= {numbers["hsync_start"]},',
        f'\t.hsync_end\t= {numbers["hsync_end"]},',
        f'\t.htotal\t\t= {numbers["htotal"]},',
        f'\t.vdisplay\t= {numbers["vdisplay"]},',
        f'\t.vsync_start\t= {numbers["vsync_start"]},',
        f'\t.vsync_end\t= {numbers["vsync_end"]},',
        f'\t.vtotal\t\t= {numbers["vtotal"]},',
        '',
        '\t.type = DRM_MODE_TYPE_DRIVER | DRM_MODE_TYPE_PREFERRED,',
        '};',
        '',
        '#endif /* __PANEL_NOVATEK_NT36523_GTS7LWIFI_H__ */',
        '',
    ]
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true',
                        help='fail when the committed header differs from the profile')
    args = parser.parse_args()

    profile = json.loads(PROFILE.read_text())
    header = emit(profile)
    if args.check:
        current = HEADER.read_text() if HEADER.is_file() else ''
        if current != header:
            raise SystemExit(f'{HEADER.relative_to(ROOT)} is stale: run scripts/steamos/emit-panel-seq.py')
        print(f'{HEADER.relative_to(ROOT)} is up to date ({len(header.splitlines())} lines)')
        return
    HEADER.write_text(header)
    numbers = mode_numbers(profile)
    print(f'wrote {HEADER.relative_to(ROOT)}')
    print(f'  mode {numbers["hdisplay"]}x{numbers["vdisplay"]}@{numbers["fps"]} '
          f'clock {numbers["clock"]} kHz, htotal {numbers["htotal"]}, vtotal {numbers["vtotal"]}')
    print(f'  {len(profile["init_sequence"]["commands"])} init commands, '
          f'{len(header.splitlines())} lines')


if __name__ == '__main__':
    try:
        main()
    except (OSError, ValueError, KeyError) as error:
        sys.exit(f'Panel header generation failed: {error}')
