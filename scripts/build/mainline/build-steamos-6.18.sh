#!/usr/bin/env bash
# Build the mainline 6.18 kernel with the SteamOS PID-1 requirements applied on
# top of the minimal bring-up configuration. Offline; never touches a device and
# never writes outside ignored out/ and the Kbuild cache.
#
# Usage: build-steamos-6.18.sh [config|dtb|image] [extra.config ...]   (default: image)
# Extra fragments are layered after steamos-6.18.config, e.g.
#   scripts/build/mainline/build-steamos-6.18.sh image \
#       hardware/samsung/gts7lwifi/kernel/configs/steamos-display-6.18.config
set -euo pipefail

project_root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../../.." && pwd)
project_id=$(printf '%s' "$project_root" | sha256sum | cut -c1-12)
build_root=${TAB_S7_STEAMOS_BUILD_ROOT:-${XDG_CACHE_HOME:-$HOME/.cache}/tabs7linux/steamos-6.18-$project_id}
out_dir=$project_root/out/steamos-kernel-6.18
base_config=$project_root/hardware/samsung/gts7lwifi/kernel/configs/gts7lwifi-bringup.config
steamos_config=$project_root/hardware/samsung/gts7lwifi/kernel/configs/steamos-6.18.config
target=${1:-image}
shift || true
extra_configs=()
for fragment in "$@"; do
    [ -f "$fragment" ] || { echo "Missing config fragment: $fragment" >&2; exit 1; }
    extra_configs+=("$(cd -- "$(dirname -- "$fragment")" && pwd)/$(basename -- "$fragment")")
done
jobs=${JOBS:-$(nproc)}
if (( jobs > 16 )); then jobs=16; fi

case "$target" in
    config|dtb|image) ;;
    *) printf 'Usage: %s [config|dtb|image]\n' "$0" >&2; exit 2 ;;
esac
case "$build_root" in
    *' '*|*':'*) echo 'TAB_S7_STEAMOS_BUILD_ROOT must not contain spaces or colons.' >&2; exit 2 ;;
esac

# Kbuild rejects source paths with spaces. Keep edits in the project and build
# a synchronized copy in a separate directory, with all outputs out of tree.
mkdir -p "$build_root/src" "$build_root/obj" "$out_dir" "$project_root/out/logs"
export PATH="$project_root/out/tools/llvm/usr/bin:$PATH"
for tool in rsync make clang-18 ld.lld-18 llvm-ar-18 llvm-nm-18 llvm-objcopy-18 llvm-strip-18; do
    command -v "$tool" >/dev/null || { echo "Missing tool: $tool" >&2; exit 1; }
done
rsync -a --delete --exclude=.git/ "$project_root/linux-sm8250-v6.18/" "$build_root/src/"

# Later assignments win, so the SteamOS layer overrides the bring-up layer.
python3 - "$base_config" "$steamos_config" "$build_root/steamos-6.18.config" "${extra_configs[@]}" <<'PY'
from pathlib import Path
import sys

base, extra, destination, *extras = (Path(argument) for argument in sys.argv[1:])
lines, order = {}, []


def record(path):
    for line in path.read_text().splitlines():
        stripped = line.strip()
        if not stripped.startswith('CONFIG_'):
            continue
        if stripped.startswith('# '):
            symbol = stripped.split()[1]
            value = 'not set'
        else:
            symbol, _, value = stripped.partition('=')
        if symbol not in lines:
            order.append(symbol)
        lines[symbol] = (value, path.name)


record(base)
record(extra)
for path in extras:
    record(path)
layers = ' + '.join(path.name for path in (base, extra, *extras))
text = [f'# Generated by build-steamos-6.18.sh: {layers}']
current = None
for symbol in order:
    value, origin = lines[symbol]
    if origin != current:
        # KCONFIG_ALLCONFIG takes no trailing comments: annotate on its own line.
        text.append(f'# from {origin}')
        current = origin
    text.append(f'# {symbol} is not set' if value == 'not set' else f'{symbol}={value}')
destination.write_text('\n'.join(text) + '\n')
print(f'Merged {len(order)} requested settings into {destination}')
PY

kmake=(make -C "$build_root/src" O="$build_root/obj" ARCH=arm64 LLVM=-18)
"${kmake[@]}" KCONFIG_ALLCONFIG="$build_root/steamos-6.18.config" allnoconfig

# Kconfig silently drops a request when dependencies are missing; reject that
# instead of shipping a kernel that is missing SYSVIPC, F2FS or systemd support.
python3 - "$build_root/steamos-6.18.config" "$build_root/obj/.config" "$out_dir/config-review.txt" <<'PY'
from pathlib import Path
import sys

requested_path, actual_path, report_path = (Path(argument) for argument in sys.argv[1:])
actual = set(actual_path.read_text().splitlines())
requested, missing = [], []
for line in requested_path.read_text().splitlines():
    stripped = line.split('  #')[0]
    if not stripped.startswith(('CONFIG_', '# CONFIG_')):
        continue
    requested.append(stripped)
    if stripped not in actual:
        missing.append(stripped)
report_path.write_text('\n'.join(requested) + '\n')
if missing:
    raise SystemExit('Kconfig did not retain:\n' + '\n'.join(missing))
print(f'All {len(requested)} requested settings retained.')
PY

if [[ "$target" == config ]]; then
    cp "$build_root/obj/.config" "$out_dir/kernel.config"
    printf 'Configuration only: %s/kernel.config\n' "$out_dir"
    exit 0
fi

"${kmake[@]}" -j"$jobs" qcom/sm8250-samsung-gts7lwifi.dtb
cp "$build_root/obj/arch/arm64/boot/dts/qcom/sm8250-samsung-gts7lwifi.dtb" "$out_dir/"
if [[ "$target" == image ]]; then
    "${kmake[@]}" -j"$jobs" Image.gz
    cp "$build_root/obj/arch/arm64/boot/Image" "$build_root/obj/arch/arm64/boot/Image.gz" "$out_dir/"
fi
cp "$build_root/obj/.config" "$out_dir/kernel.config"

python3 - "$out_dir" "$target" "${extra_configs[@]}" <<'PY'
from pathlib import Path
import hashlib
import json
import struct
import sys

out_dir = Path(sys.argv[1])
target = sys.argv[2]
extras = [Path(argument).name for argument in sys.argv[3:]]


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


artifacts = {path.name: {'bytes': path.stat().st_size, 'sha256': sha(path)}
             for path in sorted(out_dir.iterdir()) if path.is_file() and path.name != 'manifest.json'}
version = 'unknown'
image = out_dir / 'Image'
if image.is_file():
    data = image.read_bytes()
    # arm64 Image header: text_offset, image_size, flags, res2, res3, res4,
    # magic at 0x38, then the version string at 0x08 of the link-time string area.
    magic = struct.unpack_from('<I', data, 0x38)[0]
    if magic != 0x644d5241:
        raise SystemExit('Image magic mismatch')
    version = data[data.find(b'Linux version'):data.find(b'Linux version') + 96].split(b'\0')[0].decode()
manifest = {'kind': 'mainline 6.18 SteamOS kernel', 'target': target,
            'base_config': 'hardware/samsung/gts7lwifi/kernel/configs/gts7lwifi-bringup.config',
            'steamos_config': 'hardware/samsung/gts7lwifi/kernel/configs/steamos-6.18.config',
            'extra_configs': extras,
            'kernel_version': version, 'artifacts': artifacts,
            'device_write_performed': False, 'hardware_boot_observed': False,
            'notes': ['mainline 6.18 has never booted on this device',
                      'the initramfs userdata lookup still reads uevent PARTNAME, which mainline does not provide']}
(out_dir / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
print(f'{target}: {version}')
for name, info in artifacts.items():
    print(f'  {name:<31} {info["sha256"]}')
PY
printf 'Artifacts: %s\n' "$out_dir"
